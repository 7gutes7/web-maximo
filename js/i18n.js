function translateTableHeader(header, lang) {
  if (!header || lang === "es") return header;
  return FICHA_DICTIONARY.headers[header]?.[lang] || header;
}

function translateTableConcept(concept, lang) {
  if (!concept || lang === "es") return concept;
  return FICHA_DICTIONARY.concepts[concept]?.[lang] || concept;
}

function translateTableValue(val, lang) {
  if (!val || lang === "es" || typeof val !== "string") return val;
  const trimmed = val.trim();
  if (FICHA_DICTIONARY.values[trimmed]?.[lang]) {
    return FICHA_DICTIONARY.values[trimmed][lang];
  }
  let result = val;
  for (const [esKey, trans] of Object.entries(FICHA_DICTIONARY.values)) {
    if (trans[lang] && result.includes(esKey)) {
      result = result.replace(new RegExp(esKey, "g"), trans[lang]);
    }
  }
  return result;
}

let currentLang = localStorage.getItem("vm_lang_pref") || "es";

function toggleLangDropdown(event) {
  if (event) {
    event.preventDefault();
    event.stopPropagation();
  }
  const menu = document.getElementById("lang-dropdown-menu");
  if (menu) {
    menu.classList.toggle("active");
  }
}

function setLanguage(lang) {
  if (!VM_TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem("vm_lang_pref", lang);

  // 1. Update button label
  const labelEl = document.getElementById("lang-current-label");
  if (labelEl) {
    labelEl.textContent = lang.toUpperCase();
  }

  // 2. Update active state in dropdown
  const opts = document.querySelectorAll(".lang-opt");
  opts.forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("onclick")?.includes("('" + lang + "')"));
  });

  // 3. Apply translations to all tagged DOM elements
  const dict = VM_TRANSLATIONS[lang];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("placeholder")) el.placeholder = dict[key];
      } else {
        el.innerHTML = dict[key];
      }
    }
  });

  // 4. Translate dynamic badge labels on catalog cards ("DISPONIBLES" / "AVAILABLE" / "席位可租")
  document.querySelectorAll(".catalog-content .badge-open, .ficha-modal .badge-open").forEach(badge => {
    const text = badge.textContent.trim();
    const countMatch = text.match(/\d+/);
    const count = countMatch ? countMatch[0] : "";
    if (lang === "en") {
      badge.textContent = (count ? count + " " : "") + "AVAILABLE";
    } else if (lang === "zh") {
      badge.textContent = (count ? count + " " : "") + "席位可租";
    } else {
      badge.textContent = (count ? count + " " : "") + "DISPONIBLES";
    }
  });

  document.querySelectorAll(".catalog-content .badge-orange").forEach(badge => {
    const text = badge.textContent.trim();
    const countMatch = text.match(/\d+/);
    const count = countMatch ? countMatch[0] : "0";
    if (lang === "en") {
      badge.textContent = count + " AVAILABLE";
    } else if (lang === "zh") {
      badge.textContent = count + " 席位可租";
    } else {
      badge.textContent = count + " DISPONIBLES";
    }
  });

  // 5. Translate dynamic buttons on catalog cards
  document.querySelectorAll(".catalog-actions button.btn-dark").forEach(btn => {
    btn.textContent = dict["catalog_btn_request"] || "Solicitar Ficha Detallada";
  });
  document.querySelectorAll(".catalog-actions button.btn-details").forEach(btn => {
    btn.textContent = dict["catalog_btn_details"] || "Detalles";
  });

  // 6. Refresh plazas select in drawer
  if (typeof window.populatePlazasSelect === "function") {
    window.populatePlazasSelect();
  }

  // 7. If Ficha Modal is currently open, re-render its tables dynamically
  const modalOverlay = document.getElementById("ficha-modal-overlay");
  if (modalOverlay && modalOverlay.classList.contains("active") && window.lastOpenedFichaKey && window.openFichaModal) {
    window.openFichaModal(window.lastOpenedFichaKey);
  }

  // 7. Close dropdown
  const menu = document.getElementById("lang-dropdown-menu");
  if (menu) menu.classList.remove("active");

  // 8. Dispatch event
  window.dispatchEvent(new CustomEvent("vm:languageChanged", { detail: { lang, dict } }));

  console.log("🌐 Idioma actualizado a:", lang);
}

